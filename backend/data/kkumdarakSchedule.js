function sessionsByProgram(programKey) {
  return SCHEDULE_TRACKS.filter((t) => t.programKey === programKey)
    .flatMap((t) => t.sessions.map((s) => ({ ...s, track: t })))
    .sort((a, b) => a.webNo - b.webNo);
}

