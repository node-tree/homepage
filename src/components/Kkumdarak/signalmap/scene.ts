import type { Pt } from './wobble';

export const SCENE_W = 1440;
export const SCENE_H = 900;

export interface Stroke {
  pts?: Pt[];                       // 폴리라인 (blob과 택1)
  blob?: { cx: number; cy: number; rx: number; ry: number; irr?: number };
  w?: number;                       // 선 굵기 (기본 1.8)
  color?: 'ink' | 'gray';
  dash?: [number, number];
  fill?: 'ink' | 'white';           // fill이 있으면 채움(별빛 마당·별)
  amp?: number;                     // 지터 진폭 오버라이드
}

export type Actor =
  | { type: 'drive'; path: Pt[]; period: number; phase?: number }
  | { type: 'walk'; path: Pt[]; period: number; phase?: number }
  | { type: 'spin'; c: Pt; r: number; period: number }
  | { type: 'sway'; kind: 'tree' | 'flag'; at: Pt; period: number; phase?: number }
  | { type: 'smoke'; at: Pt; period: number; phase?: number }
  | { type: 'ripple'; c: Pt; rx: number; ry: number; period: number }
  | { type: 'arc'; from: Pt; ctrl: Pt; to: Pt; period: number }
  | { type: 'pulse'; path: Pt[]; period: number; phase?: number }
  | { type: 'blink'; at: Pt; r: number; period: number; phase?: number };

export interface Signal {
  id: string;
  name: string;
  pos: Pt;
  blink: [number, number];          // LED 리듬 [on,off] ms — 작품마다 다르다
  draft?: boolean;                  // true면 이름·사진만 노출(콘텐츠 후입력)
  makers?: string;
  story?: string;
  photos?: string[];                // ImageKit URL
  audio?: string;                   // ImageKit URL — 참여자 녹음 정본
}

